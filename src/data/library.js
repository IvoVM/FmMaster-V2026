export function mediaSlug(filename) {
  return filename
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/\.[^.]+$/, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

export function slidePaths(index) {
  const n = String(index + 1).padStart(2, "0");
  return {
    src: `/media/carousel/slide-${n}.webp`,
    thumb: `/media/carousel/thumb-${n}.webp`,
  };
}

export function teamPhoto(file) {
  return `/media/team/${mediaSlug(file)}.webp`;
}
